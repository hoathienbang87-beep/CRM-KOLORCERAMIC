import fs from "node:fs";
import assert from "node:assert/strict";
import { productDecimal, productQuantity, productMoney, productFromCanonical, productChanges, productError } from "../js/features/product-catalog.js";
const read = f => fs.readFileSync(new URL('../'+f,import.meta.url),'utf8');
const app=read('js/features/crm-app.js'), html=read('index.html'), shell=read('js/components/app-shell.js'), sql=read('supabase-phase-crm-products-r1-lightweight-catalog.sql');
let checks=0;
const check=(value,message)=>{assert.ok(value,message);checks++;};
check(shell.includes('id="productsViewBtn"'),'Nav sản phẩm');
check(html.includes('id="productsPanel"'),'Panel sản phẩm');
for(const id of ['quotesViewBtn','ordersViewBtn','inventoryViewBtn','paymentsViewBtn','suppliersViewBtn']) check(!(html+shell).includes(`id="${id}"`),'Không khôi phục ERP nav '+id);
for(const id of ['productFilterSize','productFilterSurface','productFilterOrigin','editProductBtn']) check(html.includes(`id="${id}"`),id);
const feature=app.slice(app.indexOf('let productDrawerEditingId'),app.indexOf('const quoteStatusOptions'));
check(!/product_inventory_balance|inventory_movements|updatedByEmail|setDoc\(/.test(feature),'Không ERP/direct write/client actor trong Product R1');
check(!app.includes('function importProductRows('),'CSV direct write đã retired');
for(const name of ['crm_update_product','crm_create_product','crm_list_products'])check(feature.includes(name),'RPC '+name);
check(feature.indexOf('await callCrmRpc("crm_update_product"')<feature.indexOf('notice("Đã lưu sản phẩm.")'),'Chỉ thành công sau server');
check(!/\b(?:delete from|truncate|drop table)\b/i.test(sql),'Không xóa dữ liệu');
check(sql.includes('stock_quantity numeric'),'Stock numeric');
check(!/stock_quantity\s+numeric\s+(?:default|not null)/i.test(sql),'Stock nullable không default 0');
check(sql.includes('jsonb_object_keys(p_changes)')&&sql.includes('jsonb_object_keys(p_product)'),'Allowlist payload');
check(sql.includes('coalesce(v_old.is_deleted, false)'),'Deleted guard');
check(sql.includes('where p_changes ? e.key'),'Partial JSON merge');
check(sql.includes('auth.uid() is null'),'Auth required');
check(sql.includes("'stock_quantity',p.stock_quantity::text"),'Read exact decimal');
check(sql.includes("'price', v_price::text"),'Response exact decimal');
check(productQuantity(null)==='Chưa cập nhật','NULL stock');
check(productQuantity('0')==='0','Zero stock');
check(productMoney('325000.125')==='325.000,125 ₫','Decimal vi-VN');
check(productDecimal('125.500000000000000001')==='125.500000000000000001','Không mất precision');
for(const value of ['-1','NaN','Infinity','325.000,5','abc','1e3']){assert.throws(()=>productDecimal(value));checks++;}
const old={id:'p1',code:'A',name:'Name',size:'S',surface:'M',origin:'VN',price:'0',stockQuantity:null};
assert.deepEqual(productChanges({...old,price:'0',stock_quantity:'',name:'New'},old),{name:'New'});checks++;
const unknown=productFromCanonical({id:'p1',updated_by_user_id:null,updated_by_name:'fake'});
check(unknown.updatedByName==='','Không bịa updater');
check(productError({message:'SQL secret table'})==='Không thể lưu thay đổi.','Không lộ lỗi SQL');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);check(new Set(ids).size===ids.length,'HTML IDs unique');
console.log(`Product R1 static/helper PASS (${checks} checks).`);
