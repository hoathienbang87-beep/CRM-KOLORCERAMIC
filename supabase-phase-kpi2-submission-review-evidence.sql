create or replace function public.crm_kpi_can_read_assignment_runtime(p_assignment_id uuid)
returns boolean language sql security definer set search_path = public stable
as $$
  select public.crm_kpi_is_business_manager() or exists (
    select 1 from public.kpi_assignments a join public.kpi_periods p on p.id = a.period_id
    where a.id = p_assignment_id and a.employee_id = public.crm_current_app_user_id()
      and a.assignment_status = 'ASSIGNED' and p.status in ('ACTIVE', 'CLOSED')
  );
$$;

create or replace function public.crm_kpi_can_read_event(p_event_id uuid)
returns boolean language sql security definer set search_path = public stable
as $$
  select exists (select 1 from public.kpi_submission_events e where e.id = p_event_id
    and public.crm_kpi_can_read_assignment_runtime(e.assignment_id));
$$;

revoke all on function public.crm_kpi_can_read_assignment_runtime(uuid) from public, anon;
revoke all on function public.crm_kpi_can_read_event(uuid) from public, anon;
grant execute on function public.crm_kpi_can_read_assignment_runtime(uuid) to authenticated;
grant execute on function public.crm_kpi_can_read_event(uuid) to authenticated;

