create or replace function public.crm_kpi_refresh_submission_status(p_submission_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_total integer; v_final integer; v_reviewed integer;
begin
  select count(*),count(*) filter(where status in ('APPROVED','REJECTED')),count(*) filter(where status<>'PENDING')
  into v_total,v_final,v_reviewed from public.kpi_submission_events where submission_id=p_submission_id;
  update public.kpi_submissions set status=case when v_total>0 and v_final=v_total then 'COMPLETED'
    when v_reviewed>0 then 'PARTIALLY_REVIEWED' else 'OPEN_REVIEW' end,
    updated_at=now(),lock_version=lock_version+1 where id=p_submission_id;
end $$;
revoke all on function public.crm_kpi_refresh_submission_status(uuid) from public,anon,authenticated;

create or replace function public.crm_kpi_review_events(
  p_request_id uuid, p_rows jsonb, p_decision text, p_reason_code text, p_manager_note text
) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_actor text:=public.crm_current_app_user_id(); v_decision text:=upper(btrim(coalesce(p_decision,'')));
  v_reason text:=upper(nullif(btrim(coalesce(p_reason_code,'')),'')); v_existing jsonb; v_row jsonb;
  v_event public.kpi_submission_events%rowtype; v_ids uuid[]; v_submission_ids uuid[]:='{}'; v_result jsonb:='[]'::jsonb;
begin
  if not public.crm_kpi_is_business_manager() or p_request_id is null then raise exception using errcode='42501', message='Chỉ manager/admin/owner được review KPI.'; end if;
  select response into v_existing from public.kpi_action_requests where actor_user_id=v_actor and action='event_review' and request_id=p_request_id;
  if v_existing is not null then return v_existing; end if;
  if v_decision not in ('APPROVED','REJECTED','NEEDS_REVISION') then raise exception using errcode='22023', message='Decision không hợp lệ.'; end if;
  if jsonb_typeof(p_rows)<>'array' or jsonb_array_length(p_rows) not between 1 and 100 then raise exception using errcode='22023', message='Review cần 1-100 event.'; end if;
  if jsonb_array_length(p_rows)<>(select count(distinct value->>'eventId') from jsonb_array_elements(p_rows)) then raise exception using errcode='22023', message='Danh sách event bị trùng.'; end if;
  if v_decision='REJECTED' and v_reason not in ('DUPLICATE','INVALID_EVIDENCE','MISSING_LOCATION','MISSING_TIMESTAMP','INCOMPLETE_INFORMATION','NOT_NEW','OUT_OF_SCOPE','OTHER')
    then raise exception using errcode='22023', message='Từ chối cần reason code hợp lệ.'; end if;
  if (v_decision='NEEDS_REVISION' or v_reason='OTHER') and nullif(btrim(coalesce(p_manager_note,'')),'') is null
    then raise exception using errcode='22023', message='Cần ghi chú Manager cho NEEDS_REVISION/OTHER.'; end if;
  select array_agg((x->>'eventId')::uuid order by x->>'eventId') into v_ids from jsonb_array_elements(p_rows) x;
  -- Lock all rows in deterministic order, then validate all before the first update.
  perform 1 from public.kpi_submission_events e where e.id=any(v_ids) order by e.id for update;
  if (select count(*) from public.kpi_submission_events where id=any(v_ids))<>cardinality(v_ids) then raise exception using errcode='P0002', message='Có event không tồn tại.'; end if;
  for v_row in select value from jsonb_array_elements(p_rows) loop
    select e.* into v_event from public.kpi_submission_events e join public.kpi_assignments a on a.id=e.assignment_id
      join public.app_users u on u.id=a.employee_id where e.id=(v_row->>'eventId')::uuid and lower(u.role)='sale';
    if v_event.id is null then raise exception using errcode='42501', message='Manager chỉ review KPI của sale.'; end if;
    if v_event.status<>'PENDING' then raise exception using errcode='55000', message='EVENT_VERSION_CONFLICT: Event đã được xử lý.'; end if;
    if v_event.lock_version<>coalesce((v_row->>'expectedVersion')::integer,0) then raise exception using errcode='P0001', message='EVENT_VERSION_CONFLICT: Event đã thay đổi.'; end if;
  end loop;
  perform set_config('crm.kpi_write','on',true);
  for v_row in select value from jsonb_array_elements(p_rows) loop
    update public.kpi_submission_events set status=v_decision,
      approved_value=case when v_decision='APPROVED' then claimed_value else null end,
      review_reason_code=case when v_decision='APPROVED' then null else v_reason end,
      manager_note=nullif(btrim(coalesce(p_manager_note,'')),''),reviewed_by_user_id=v_actor,reviewed_at=now(),updated_at=now(),lock_version=lock_version+1
    where id=(v_row->>'eventId')::uuid returning * into v_event;
    if not(v_event.submission_id=any(v_submission_ids)) then v_submission_ids:=array_append(v_submission_ids,v_event.submission_id); end if;
    perform public.crm_kpi_write_audit(case v_decision when 'APPROVED' then 'event_approve' when 'REJECTED' then 'event_reject' else 'event_needs_revision' end,
      'kpi_submission_events',v_event.id::text,jsonb_build_object('periodId',(select period_id from public.kpi_assignments where id=v_event.assignment_id),
        'assignmentId',v_event.assignment_id,'submissionId',v_event.submission_id,'eventId',v_event.id,'employeeId',v_event.actor_user_id,
        'decision',v_decision,'reason',v_reason,'managerNote',p_manager_note,'after',to_jsonb(v_event)));
    v_result:=v_result||jsonb_build_array(jsonb_build_object('eventId',v_event.id,'status',v_event.status,'lockVersion',v_event.lock_version));
  end loop;
  foreach v_event.submission_id in array v_submission_ids loop perform public.crm_kpi_refresh_submission_status(v_event.submission_id); end loop;
  v_existing:=jsonb_build_object('decision',v_decision,'count',jsonb_array_length(v_result),'events',v_result);
  insert into public.kpi_action_requests(actor_user_id,action,request_id,response) values(v_actor,'event_review',p_request_id,v_existing);
  perform public.crm_kpi_write_audit('bulk_review','kpi_submission_events','bulk',jsonb_build_object('requestId',p_request_id,'decision',v_decision,'reason',v_reason,'events',v_result));
  return v_existing;
end $$;

create or replace function public.crm_kpi_get_assignment_progress(p_period_id uuid default null)
returns table(
  assignment_id uuid, period_id uuid, period_month date, period_status text, definition_id uuid,
  employee_id text, employee_name text, definition_snapshot jsonb, target numeric, score_enabled boolean,
  aggregation_mode text, approved_actual numeric, pending_count bigint, pending_value numeric,
  needs_revision_count bigint, needs_revision_value numeric, rejected_count bigint, rejected_value numeric,
  actual_completion_pct numeric, scoring_completion_pct numeric, has_open_items boolean
) language sql security definer set search_path = public stable as $$
  select a.id,p.id,p.period_month,p.status,a.definition_id,a.employee_id,u.name,a.definition_snapshot,a.target,a.score_enabled,
    coalesce(a.definition_snapshot->>'aggregation_mode','COUNT'),
    coalesce(sum(e.approved_value) filter(where e.status='APPROVED'),0),
    count(e.id) filter(where e.status='PENDING'),coalesce(sum(e.claimed_value) filter(where e.status='PENDING'),0),
    count(e.id) filter(where e.status='NEEDS_REVISION'),coalesce(sum(e.claimed_value) filter(where e.status='NEEDS_REVISION'),0),
    count(e.id) filter(where e.status='REJECTED'),coalesce(sum(e.claimed_value) filter(where e.status='REJECTED'),0),
    round(coalesce(sum(e.approved_value) filter(where e.status='APPROVED'),0)/a.target*100,2),
    least(round(coalesce(sum(e.approved_value) filter(where e.status='APPROVED'),0)/a.target*100,2),100),
    count(e.id) filter(where e.status in ('PENDING','NEEDS_REVISION'))>0
  from public.kpi_assignments a join public.kpi_periods p on p.id=a.period_id join public.app_users u on u.id=a.employee_id
  left join public.kpi_submission_events e on e.assignment_id=a.id
  where a.assignment_status='ASSIGNED' and p.status in ('ACTIVE','CLOSED') and (p_period_id is null or p.id=p_period_id)
    and (public.crm_kpi_is_business_manager() or a.employee_id=public.crm_current_app_user_id())
  group by a.id,p.id,u.name;
$$;

create or replace function public.crm_kpi_get_monthly_scores(p_period_id uuid)
returns table(employee_id text, employee_name text, included_kpi_count bigint, monthly_score numeric, has_open_items boolean)
language sql security definer set search_path = public stable as $$
  select x.employee_id,x.employee_name,count(*) filter(where x.score_enabled),
    round(coalesce(avg(x.scoring_completion_pct) filter(where x.score_enabled),0),2),
    bool_or(x.has_open_items)
  from public.crm_kpi_get_assignment_progress(p_period_id) x group by x.employee_id,x.employee_name;
$$;

