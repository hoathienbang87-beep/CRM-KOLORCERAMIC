create or replace function public.crm_kpi_create_definition_v2(
  p_code text, p_name text, p_description text, p_kpi_type text,
  p_source_metric_key text, p_unit text, p_submission_mode text,
  p_evidence_required boolean, p_aggregation_mode text,
  p_max_images_per_event integer, p_location_required boolean,
  p_timestamp_required boolean
) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_actor text := public.crm_current_app_user_id(); v_row public.kpi_definitions%rowtype;
  v_code text := upper(btrim(coalesce(p_code,''))); v_type text := upper(btrim(coalesce(p_kpi_type,'')));
  v_mode text := upper(btrim(coalesce(p_submission_mode,'EVENT_CLAIM'))); v_agg text := upper(btrim(coalesce(p_aggregation_mode,'COUNT')));
begin
  if not public.crm_kpi_is_business_manager() then raise exception using errcode='42501', message='Chỉ manager/admin/owner được tạo KPI.'; end if;
  if v_code !~ '^[A-Z][A-Z0-9_]{1,63}$' or nullif(btrim(coalesce(p_name,'')),'') is null or nullif(btrim(coalesce(p_unit,'')),'') is null
    then raise exception using errcode='22023', message='Mã, tên hoặc đơn vị KPI không hợp lệ.'; end if;
  if v_type not in ('AUTO','MANUAL','HYBRID') or v_mode <> 'EVENT_CLAIM' or v_agg not in ('COUNT','SUM')
    then raise exception using errcode='22023', message='Cấu hình loại/aggregation KPI không hợp lệ.'; end if;
  if coalesce(p_max_images_per_event,2) not between 0 and 2 then raise exception using errcode='22023', message='Tối đa 0-2 ảnh mỗi event.'; end if;
  perform set_config('crm.kpi_write','on',true);
  insert into public.kpi_definitions(code,name,description,kpi_type,source_metric_key,unit,submission_mode,evidence_required,
    aggregation_mode,max_images_per_event,location_required,timestamp_required,active,created_by_user_id,updated_by_user_id)
  values(v_code,btrim(p_name),nullif(btrim(coalesce(p_description,'')),''),v_type,nullif(btrim(coalesce(p_source_metric_key,'')),''),btrim(p_unit),
    v_mode,coalesce(p_evidence_required,false),v_agg,coalesce(p_max_images_per_event,2),coalesce(p_location_required,false),
    coalesce(p_timestamp_required,true),true,v_actor,v_actor) returning * into v_row;
  perform public.crm_kpi_write_audit('definition_create','kpi_definitions',v_row.id::text,jsonb_build_object('after',to_jsonb(v_row),'phase','KPI-2'));
  return to_jsonb(v_row);
exception when unique_violation then raise exception using errcode='23505', message='Mã KPI đã tồn tại.';
end $$;

create or replace function public.crm_kpi_update_assignment_options(
  p_assignment_id uuid, p_score_enabled boolean, p_expected_assignment_version integer, p_expected_period_version integer
) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_old public.kpi_assignments%rowtype; v_new public.kpi_assignments%rowtype; v_period public.kpi_periods%rowtype;
begin
  if not public.crm_kpi_is_business_manager() then raise exception using errcode='42501', message='Không có quyền sửa tùy chọn KPI.'; end if;
  select * into v_old from public.kpi_assignments where id=p_assignment_id for update;
  if v_old.id is null then raise exception using errcode='P0002', message='Không tìm thấy assignment.'; end if;
  select * into v_period from public.kpi_periods where id=v_old.period_id for update;
  if v_period.status <> 'DRAFT' then raise exception using errcode='55000', message='Chỉ kỳ DRAFT được sửa.'; end if;
  if v_old.lock_version <> p_expected_assignment_version or v_period.version <> p_expected_period_version then
    raise exception using errcode='P0001', message='KPI_VERSION_CONFLICT: Dữ liệu đã thay đổi.'; end if;
  perform set_config('crm.kpi_write','on',true);
  update public.kpi_assignments set score_enabled=coalesce(p_score_enabled,true),updated_at=now(),lock_version=lock_version+1
    where id=p_assignment_id returning * into v_new;
  update public.kpi_periods set version=version+1,updated_at=now() where id=v_old.period_id;
  perform public.crm_kpi_write_audit('assignment_options_update','kpi_assignments',v_new.id::text,
    jsonb_build_object('before',to_jsonb(v_old),'after',to_jsonb(v_new),'periodVersion',v_period.version+1));
  return to_jsonb(v_new)||jsonb_build_object('periodVersion',v_period.version+1);
end $$;

