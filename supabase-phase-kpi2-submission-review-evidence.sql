create or replace function public.crm_kpi_submit_events(
  p_assignment_id uuid, p_request_id uuid, p_sale_note text, p_events jsonb
) returns jsonb language plpgsql security definer set search_path = public, storage as $$
declare v_actor text:=public.crm_current_app_user_id(); v_a public.kpi_assignments%rowtype; v_p public.kpi_periods%rowtype;
  v_s public.kpi_submissions%rowtype; v_event jsonb; v_e public.kpi_submission_events%rowtype; v_snapshot jsonb;
  v_source_type text; v_source_id text; v_source_key text; v_event_at timestamptz; v_customer_id text;
  v_value numeric; v_agg text; v_type text; v_evidence jsonb; v_evidence_id uuid; v_count integer; v_location jsonb;
  v_duplicate jsonb; v_ids jsonb:='[]'::jsonb; v_existing jsonb;
begin
  if not public.crm_is_active_user() or p_request_id is null then raise exception using errcode='42501', message='Yêu cầu submit không hợp lệ.'; end if;
  select response into v_existing from public.kpi_action_requests where actor_user_id=v_actor and action='submission_create' and request_id=p_request_id;
  if v_existing is not null then return v_existing; end if;
  select * into v_a from public.kpi_assignments where id=p_assignment_id for update;
  if v_a.id is null or v_a.employee_id<>v_actor or v_a.assignment_status<>'ASSIGNED' then raise exception using errcode='42501', message='Bạn chỉ submit KPI được giao cho mình.'; end if;
  select * into v_p from public.kpi_periods where id=v_a.period_id for share;
  if v_p.status<>'ACTIVE' then raise exception using errcode='55000', message='Chỉ kỳ KPI ACTIVE nhận submission.'; end if;
  if jsonb_typeof(p_events)<>'array' or jsonb_array_length(p_events) not between 1 and 50 then raise exception using errcode='22023', message='Mỗi submission cần 1-50 event.'; end if;
  v_agg:=coalesce(v_a.definition_snapshot->>'aggregation_mode','COUNT'); v_type:=coalesce(v_a.definition_snapshot->>'kpi_type','MANUAL');
  perform set_config('crm.kpi_write','on',true);
  insert into public.kpi_submissions(assignment_id,request_id,submitted_by_user_id,sale_note)
  values(v_a.id,p_request_id,v_actor,nullif(btrim(coalesce(p_sale_note,'')),'')) returning * into v_s;

  for v_event in select value from jsonb_array_elements(p_events) loop
    v_source_type:=upper(btrim(coalesce(v_event->>'sourceType','MANUAL'))); v_source_id:=nullif(btrim(v_event->>'sourceId'),'');
    if v_type in ('HYBRID','AUTO') then
      v_snapshot:=public.crm_kpi_source_snapshot(v_a.id,v_source_type,v_source_id);
      v_source_key:=v_snapshot->>'source_event_key'; v_event_at:=(v_snapshot->>'event_at')::timestamptz;
      v_customer_id:=nullif(v_snapshot->>'customer_id','');
    else
      if v_source_type<>'MANUAL' then raise exception using errcode='22023', message='KPI MANUAL chỉ nhận event MANUAL.'; end if;
      v_source_key:=nullif(btrim(v_event->>'sourceEventKey'),'');
      if v_source_key is null or v_source_key !~ '^manual:[0-9a-f-]{36}$' then raise exception using errcode='22023', message='Manual event key không hợp lệ.'; end if;
      begin v_event_at:=(v_event->>'eventAt')::timestamptz; exception when others then raise exception using errcode='22023', message='Ngày event không hợp lệ.'; end;
      if v_event_at<v_p.starts_at or v_event_at>=v_p.ends_at then raise exception using errcode='22023', message='Event phải nằm trong kỳ KPI.'; end if;
      v_customer_id:=nullif(btrim(v_event->>'customerId'),'');
      v_snapshot:=coalesce(v_event->'eventSnapshot','{}'::jsonb);
      if jsonb_typeof(v_snapshot)<>'object' or nullif(btrim(coalesce(v_snapshot->>'title',v_snapshot->>'description','')),'') is null then
        raise exception using errcode='22023', message='Event MANUAL cần tiêu đề hoặc nội dung.'; end if;
    end if;
    begin v_value:=coalesce((v_event->>'claimedValue')::numeric,1); exception when others then raise exception using errcode='22023', message='Giá trị event không hợp lệ.'; end;
    if v_agg='COUNT' then v_value:=1; elsif v_value<=0 then raise exception using errcode='22023', message='Giá trị SUM phải lớn hơn 0.'; end if;
    v_location:=v_event->'location';
    if coalesce((v_a.definition_snapshot->>'location_required')::boolean,false) and
      (v_location is null or jsonb_typeof(v_location)<>'object' or not(v_location?'latitude') or not(v_location?'longitude') or not(v_location?'accuracy'))
      then raise exception using errcode='22023', message='KPI này bắt buộc vị trí hợp lệ.'; end if;
    v_evidence:=coalesce(v_event->'evidenceIds','[]'::jsonb);
    if jsonb_typeof(v_evidence)<>'array' then raise exception using errcode='22023', message='Danh sách evidence không hợp lệ.'; end if;
    v_count:=jsonb_array_length(v_evidence);
    if v_count>least(2,coalesce((v_a.definition_snapshot->>'max_images_per_event')::integer,2)) then raise exception using errcode='22023', message='Vượt quá số ảnh cho phép mỗi event.'; end if;
    if coalesce((v_a.definition_snapshot->>'evidence_required')::boolean,false) and v_count=0 then raise exception using errcode='22023', message='KPI này bắt buộc ảnh minh chứng.'; end if;
    if v_count<>(select count(*) from jsonb_array_elements_text(v_evidence)) or v_count<>(select count(distinct value) from jsonb_array_elements_text(v_evidence))
      then raise exception using errcode='22023', message='Evidence ID bị trùng hoặc không hợp lệ.'; end if;

    select coalesce(jsonb_agg(jsonb_build_object('eventId',x.id,'employeeId',a.employee_id)),'[]'::jsonb) into v_duplicate
    from public.kpi_submission_events x join public.kpi_assignments a on a.id=x.assignment_id
    where a.period_id=v_a.period_id and a.definition_id=v_a.definition_id and a.employee_id<>v_actor
      and x.source_type=v_source_type and x.source_event_key=v_source_key;
    insert into public.kpi_submission_events(submission_id,assignment_id,source_type,source_id,source_event_key,event_at,actor_user_id,
      customer_id,claimed_value,event_snapshot,location_snapshot,possible_duplicate,duplicate_context)
    values(v_s.id,v_a.id,v_source_type,v_source_id,v_source_key,v_event_at,v_actor,v_customer_id,v_value,v_snapshot,v_location,
      jsonb_array_length(v_duplicate)>0,v_duplicate) returning * into v_e;
    update public.kpi_submission_events set root_event_id=v_e.id where id=v_e.id;
    for v_evidence_id in select value::text::uuid from jsonb_array_elements_text(v_evidence) loop
      update public.kpi_evidence set event_id=v_e.id,status='ATTACHED',attached_at=now(),updated_at=now(),lock_version=lock_version+1
      where id=v_evidence_id and assignment_id=v_a.id and uploaded_by_user_id=v_actor and status='STAGED';
      if not found then raise exception using errcode='22023', message='Evidence không tồn tại, không thuộc bạn hoặc đã được dùng.'; end if;
      perform public.crm_kpi_write_audit('evidence_attach','kpi_evidence',v_evidence_id::text,jsonb_build_object('eventId',v_e.id,'submissionId',v_s.id));
    end loop;
    perform public.crm_kpi_write_audit('event_claim_create','kpi_submission_events',v_e.id::text,
      jsonb_build_object('periodId',v_a.period_id,'assignmentId',v_a.id,'definitionId',v_a.definition_id,'employeeId',v_actor,
        'submissionId',v_s.id,'eventId',v_e.id,'sourceType',v_source_type,'sourceId',v_source_id,'sourceEventKey',v_source_key,
        'claimedValue',v_value,'possibleDuplicate',jsonb_array_length(v_duplicate)>0));
    v_ids:=v_ids||jsonb_build_array(v_e.id);
  end loop;
  v_existing:=jsonb_build_object('submissionId',v_s.id,'status',v_s.status,'eventIds',v_ids,'eventCount',jsonb_array_length(v_ids));
  insert into public.kpi_action_requests(actor_user_id,action,request_id,response) values(v_actor,'submission_create',p_request_id,v_existing);
  perform public.crm_kpi_write_audit('submission_create','kpi_submissions',v_s.id::text,
    jsonb_build_object('periodId',v_a.period_id,'assignmentId',v_a.id,'definitionId',v_a.definition_id,'employeeId',v_actor,
      'submissionId',v_s.id,'requestId',p_request_id,'eventIds',v_ids));
  return v_existing;
exception when unique_violation then
  select response into v_existing from public.kpi_action_requests where actor_user_id=v_actor and action='submission_create' and request_id=p_request_id;
  if v_existing is not null then return v_existing; end if;
  raise exception using errcode='23505', message='Event đã được claim hoặc yêu cầu đã được xử lý.';
end $$;

create or replace function public.crm_kpi_submit_revision(
  p_event_id uuid, p_request_id uuid, p_sale_note text, p_event jsonb
) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_old public.kpi_submission_events%rowtype; v_payload jsonb; v_result jsonb;
begin
  select * into v_old from public.kpi_submission_events where id=p_event_id for update;
  if v_old.id is null or v_old.actor_user_id<>public.crm_current_app_user_id() or v_old.status<>'NEEDS_REVISION' then
    raise exception using errcode='42501', message='Chỉ event NEEDS_REVISION của bạn mới được gửi lại.'; end if;
  v_payload:=jsonb_build_array(coalesce(p_event,'{}'::jsonb)||jsonb_build_object(
    'sourceType',v_old.source_type,'sourceId',v_old.source_id,
    'sourceEventKey','manual:'||gen_random_uuid()::text,
    'eventAt',coalesce(p_event->>'eventAt',v_old.event_at::text),
    'customerId',coalesce(p_event->>'customerId',v_old.customer_id),
    'eventSnapshot',coalesce(p_event->'eventSnapshot',v_old.event_snapshot)||jsonb_build_object('supersedesEventId',v_old.id)
  ));
  v_result:=public.crm_kpi_submit_events(v_old.assignment_id,p_request_id,p_sale_note,v_payload);
  perform set_config('crm.kpi_write','on',true);
  update public.kpi_submission_events set supersedes_event_id=v_old.id,root_event_id=coalesce(v_old.root_event_id,v_old.id),
    revision_no=v_old.revision_no+1 where id=(v_result->'eventIds'->>0)::uuid;
  perform public.crm_kpi_write_audit('event_revision','kpi_submission_events',(v_result->'eventIds'->>0),
    jsonb_build_object('supersedesEventId',v_old.id,'newEventId',v_result->'eventIds'->>0));
  return v_result;
end $$;

