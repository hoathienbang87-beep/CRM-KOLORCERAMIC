create or replace function public.crm_kpi_stage_evidence(
  p_evidence_id uuid, p_assignment_id uuid, p_object_path text,
  p_original_name text, p_mime_type text, p_size_bytes bigint, p_sha256 text
) returns jsonb language plpgsql security definer set search_path = public, storage as $$
declare v_actor text := public.crm_current_app_user_id(); v_assignment public.kpi_assignments%rowtype;
  v_period public.kpi_periods%rowtype; v_object storage.objects%rowtype; v_row public.kpi_evidence%rowtype;
begin
  if not public.crm_is_active_user() then raise exception using errcode='42501', message='Tài khoản không hoạt động.'; end if;
  select * into v_assignment from public.kpi_assignments where id=p_assignment_id and employee_id=v_actor and assignment_status='ASSIGNED';
  if v_assignment.id is null then raise exception using errcode='42501', message='Bạn chỉ upload minh chứng cho KPI của mình.'; end if;
  select * into v_period from public.kpi_periods where id=v_assignment.period_id;
  if v_period.status <> 'ACTIVE' then raise exception using errcode='55000', message='Chỉ kỳ KPI ACTIVE nhận minh chứng.'; end if;
  if p_evidence_id is null or p_object_path <> 'kpi2/'||v_actor||'/'||p_evidence_id::text||'/'||regexp_replace(p_original_name,'[^A-Za-z0-9._-]+','_','g') then
    raise exception using errcode='22023', message='Đường dẫn minh chứng không hợp lệ.'; end if;
  if p_mime_type not in ('image/jpeg','image/webp') or p_size_bytes not between 1 and 1572864 or lower(coalesce(p_sha256,'')) !~ '^[a-f0-9]{64}$' then
    raise exception using errcode='22023', message='Ảnh phải là JPEG/WebP, tối đa 1.5MB và có SHA256 hợp lệ.'; end if;
  select * into v_object from storage.objects where bucket_id='kpi2-evidence' and name=p_object_path;
  if v_object.id is null then raise exception using errcode='P0002', message='Không tìm thấy file vừa upload.'; end if;
  perform set_config('crm.kpi_write','on',true);
  insert into public.kpi_evidence(id,assignment_id,bucket,object_path,original_name,mime_type,size_bytes,sha256,uploaded_by_user_id)
  values(p_evidence_id,p_assignment_id,'kpi2-evidence',p_object_path,p_original_name,p_mime_type,p_size_bytes,lower(p_sha256),v_actor)
  returning * into v_row;
  perform public.crm_kpi_write_audit('evidence_stage','kpi_evidence',v_row.id::text,
    jsonb_build_object('assignmentId',p_assignment_id,'bucket',v_row.bucket,'objectPath',v_row.object_path,'sizeBytes',v_row.size_bytes));
  return to_jsonb(v_row);
exception when unique_violation then
  select * into v_row from public.kpi_evidence where id=p_evidence_id and uploaded_by_user_id=v_actor;
  if v_row.id is null then raise exception using errcode='23505', message='Minh chứng đã được dùng.'; end if;
  return to_jsonb(v_row);
end $$;

create or replace function public.crm_kpi_source_snapshot(
  p_assignment_id uuid, p_source_type text, p_source_id text
) returns jsonb language plpgsql security definer set search_path = public stable as $$
declare v_assignment public.kpi_assignments%rowtype; v_period public.kpi_periods%rowtype; v_metric text;
  v_row jsonb; v_actor text := public.crm_current_app_user_id();
begin
  select * into v_assignment from public.kpi_assignments where id=p_assignment_id;
  if v_assignment.id is null or v_assignment.employee_id<>v_actor then raise exception using errcode='42501', message='Assignment không thuộc sale hiện tại.'; end if;
  select * into v_period from public.kpi_periods where id=v_assignment.period_id;
  v_metric := coalesce(v_assignment.definition_snapshot->>'source_metric_key','');
  if v_metric='care_logs_v1' and upper(p_source_type)='CARE_LOG' then
    select jsonb_build_object('source_type','CARE_LOG','source_id',l.id,'source_event_key','care_log:'||l.id,
      'event_at',l.created_at,'customer_id',l.customer_id,'customer_name',l.customer_name,'care_channel',l.care_channel,
      'care_result',l.care_result,'note',l.note,'source_updated_at',l.updated_at)
    into v_row from public.care_logs l join public.customers c on c.id=l.customer_id
    where l.id=p_source_id and not coalesce(l.is_deleted,false) and not coalesce(c.is_deleted,false)
      and c.owner_user_id=v_actor and l.created_at>=v_period.starts_at and l.created_at<v_period.ends_at;
  elsif v_metric='customers_v1' and upper(p_source_type)='CUSTOMER' then
    select jsonb_build_object('source_type','CUSTOMER','source_id',c.id,'source_event_key','customer:'||c.id,
      'event_at',c.created_at,'customer_id',c.id,'customer_name',c.name,'company_name',c.company_name,
      'phone_normalized',c.phone_normalized,'channel',c.channel,'source_updated_at',c.updated_at)
    into v_row from public.customers c where c.id=p_source_id and not coalesce(c.is_deleted,false)
      and c.owner_user_id=v_actor and c.created_at>=v_period.starts_at and c.created_at<v_period.ends_at;
  elsif v_metric='deals_v1' and upper(p_source_type)='DEAL' then
    select jsonb_build_object('source_type','DEAL','source_id',d.id,'source_event_key','deal:'||d.id,
      'event_at',coalesce(d.completed_at,d.created_at),'customer_id',d.customer_id,'customer_name',d.customer_name,
      'amount',coalesce(d.revenue,d.amount,0),'deal_status',d.deal_status,'source_updated_at',d.updated_at)
    into v_row from public.deals d join public.customers c on c.id=d.customer_id
    where d.id=p_source_id and not coalesce(d.is_deleted,false) and c.owner_user_id=v_actor
      and coalesce(d.completed_at,d.created_at)>=v_period.starts_at and coalesce(d.completed_at,d.created_at)<v_period.ends_at;
  else
    raise exception using errcode='22023', message='Source adapter chưa được hỗ trợ cho KPI này.';
  end if;
  if v_row is null then raise exception using errcode='P0002', message='Source event không tồn tại, ngoài kỳ hoặc không thuộc quyền sale.'; end if;
  return v_row;
end $$;
